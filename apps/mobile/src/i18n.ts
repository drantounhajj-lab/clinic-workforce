export const strings = { en, fr };
export type Strings = typeof en;

export function reasonText(t: Strings, reason: string | undefined, extra: { distance?: string; radius?: number; opensIn?: number }): string {
  const r = t.reasons[reason ?? ""];
  if (!r) return t.error;
  if (typeof r === "string") return r;
  if (reason === "too_early") return (r as (n: number) => string)(extra.opensIn ?? 0);
  if (reason === "outside_geofence") return (r as (d: string, n: number) => string)(extra.distance ?? "", extra.radius ?? 0);
  return t.error;
}
