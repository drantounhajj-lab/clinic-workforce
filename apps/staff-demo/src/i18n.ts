export type Strings = (typeof strings)["en"];

export function decisionMessage(d: PunchDecision, t: Strings, clinicName: string, radius: number, earlyLimit: number, lang: Lang): string {
  switch (d.reason) {
    case "too_early":
      return t.reasons.too_early(earlyLimit, d.opensInMin ?? 0);
    case "outside_geofence": {
      const m = d.distanceM ?? 0;
      const km = m >= 1000 ? `${new Intl.NumberFormat(lang === "fr" ? "fr-CA" : "en-CA", { maximumFractionDigits: 1 }).format(m / 1000)} km` : `${m} m`;
      return t.reasons.outside_geofence(km, clinicName, radius);
    }
    case "no_position":
      return t.reasons.no_position;
    case "invalid_qr":
      return t.reasons.invalid_qr;
    case "mock_location":
      return t.reasons.mock_location;
    default:
      return "";
  }
}
